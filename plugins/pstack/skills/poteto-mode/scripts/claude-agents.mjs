import * as core from "./agent-routes.mjs";

export const marker = "<!-- Generated by pstack Claude Code routing. -->";
export const efforts = ["low", "medium", "high", "xhigh", "max"];

// The Agent tool carries a model but no effort, so only a pair with explicit effort needs a generated
// agent; a pair without one keeps the calling skill's subagent_type and passes model on the call.
export const claude = {
  id: "pstack-claude",
  harness: "claude",
  marker,
  route(label, { model, effort }) {
    if (model !== null && !/^[a-z0-9][a-z0-9.-]*(\[1m\])?$/.test(model)) {
      throw new Error(`Invalid model assignment for ${label}: ${model}`);
    }
    if (effort === null) return { target: { agent: null, model: model ?? "inherit-parent", effort: null } };
    if (!efforts.includes(effort)) {
      throw new Error(`Unsupported Claude Code effort for ${label}: ${effort} (use ${efforts.join(", ")})`);
    }
    const reference = `${model ?? "inherit"}@${effort}`;
    const agent = core.agentName(reference);
    return {
      target: { agent, model: model ?? "inherit-parent", effort },
      profile: { agent, key: reference, text: profileText(agent, model ?? "inherit", effort) },
    };
  },
};

export function profileText(agent, model, effort) {
  return `---
name: ${agent}
description: Pstack worker routed to ${model} at ${effort} effort. Use for roles assigned to this model and effort in pstack-models.md.
model: ${model}
effort: ${effort}
---

${core.workerBrief(marker)}`;
}

export const routesFromSheet = (text) => core.routesFromSheet(text, claude);
export const installProfiles = (mapping, configDir, options) => core.installProfiles(mapping, configDir, claude, options);
export const main = (args) => core.main(args, claude);

core.runIfMain(import.meta.url, claude);
