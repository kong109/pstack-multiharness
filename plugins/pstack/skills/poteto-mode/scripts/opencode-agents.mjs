import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { parseArgs } from "node:util";

import { resolveRole } from "./resolve-models.mjs";

const marker = "<!-- Generated by pstack OpenCode routing. -->";
const skill = fileURLToPath(new URL("../SKILL.md", import.meta.url));

export function routesFromSheet(text) {
  const routes = {};
  const profiles = new Map();
  for (const line of text.split("\n")) {
    const row = line.trim().match(/^([a-z][a-z ,\/-]*):\s*(\S.*)$/);
    if (!row) continue;
    const [, label] = row;
    if (label === "effort") continue;
    const targets = resolveRole(text, label).map(({ model, effort: variant }) => {
      if (model === null) {
        if (variant !== null) throw new Error(`Cannot apply explicit effort to inherited OpenCode model for ${label}`);
        return { agent: "general", model: "inherit-parent" };
      }
      if (!/^[a-z0-9._-]+\/[a-z0-9._-]+$/.test(model)) {
        throw new Error(`Invalid model assignment for ${label}: ${model}`);
      }
      if (variant !== null && !/^[a-z0-9_-]+$/.test(variant)) {
        throw new Error(`Invalid reasoning variant for ${model}`);
      }
      const reference = variant === null ? model : `${model}#${variant}`;
      const agent = `pstack-${reference.replace(/[^a-z0-9]+/g, "-")}`;
      if (profiles.has(agent) && profiles.get(agent) !== reference) {
        throw new Error(`Agent name collision: ${agent}`);
      }
      profiles.set(agent, reference);
      return { agent, model, variant };
    });
    for (const role of [label, ...label.split(",").map((value) => value.trim())]) {
      if (routes[role] && JSON.stringify(routes[role]) !== JSON.stringify(targets)) {
        throw new Error(`Conflicting assignment for ${role}`);
      }
      routes[role] = targets;
    }
  }
  if (Object.keys(routes).length === 0) throw new Error("No role assignments found");
  return { routes, profiles };
}

export function profileText(reference) {
  return `---
description: Pstack worker routed to ${reference}. Use for roles assigned to this model in pstack-models.md.
mode: subagent
model: ${reference}
---

${marker}

Follow the parent's assigned task and scope. Read the poteto-mode instructions at ${skill} before working. If the task supplies a specialist prompt or reference, read it and preserve that specialty. Do not replace the assigned task with an unrelated workflow. Report evidence and limitations accurately.
`;
}

export function installProfiles(mapping, configDir, { check = false } = {}) {
  const { routes, profiles } = routesFromSheet(readFileSync(mapping, "utf8"));
  const files = [...profiles].map(([agent, reference]) => [join(configDir, "agents", `${agent}.md`), profileText(reference)]);
  const manifest = join(configDir, "pstack-routing.json");
  const content = JSON.stringify({ generatedBy: "pstack-opencode", mapping: resolve(mapping), routes }, null, 2) + "\n";
  for (const [path, expected] of files) {
    if (existsSync(path)) {
      const current = readFileSync(path, "utf8");
      if (current !== expected && !current.includes(marker)) throw new Error(`Refusing to overwrite unmanaged agent: ${path}`);
    }
  }
  if (existsSync(manifest) && JSON.parse(readFileSync(manifest, "utf8")).generatedBy !== "pstack-opencode") {
    throw new Error(`Refusing to overwrite unmanaged routing file: ${manifest}`);
  }
  const outputs = [...files, [manifest, content]];
  const stale = outputs.filter(([path, expected]) => !existsSync(path) || readFileSync(path, "utf8") !== expected);
  if (check && stale.length) throw new Error(`Pstack routing is stale in ${configDir}; rerun with --install`);
  if (!check) {
    for (const [path, expected] of stale) {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, expected);
    }
  }
  return { routes, agents: [...profiles.keys()] };
}

export function main(args) {
  const { values } = parseArgs({ args, options: {
    mapping: { type: "string" }, "config-dir": { type: "string" },
    install: { type: "boolean" }, check: { type: "boolean" }, role: { type: "string" },
  } });
  if (!values.mapping || !values["config-dir"] || (values.install && values.check)) {
    throw new Error("Use --mapping FILE --config-dir DIR with --install, --check, or --role ROLE");
  }
  if (!values.install && !values.check && !values.role) throw new Error("Choose --install, --check, or --role ROLE");
  const result = installProfiles(resolve(values.mapping), resolve(values["config-dir"]), { check: !values.install });
  if (values.role) {
    const targets = result.routes[values.role];
    if (!targets) throw new Error(`No assignment for role: ${values.role}`);
    console.log(JSON.stringify(targets, null, 2));
  } else {
    console.log(JSON.stringify({ agents: result.agents, status: values.install ? "installed" : "current" }, null, 2));
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  try { main(process.argv.slice(2)); }
  catch (error) { console.error(error.message); process.exitCode = 1; }
}
