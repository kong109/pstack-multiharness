import * as core from "./agent-routes.mjs";

export const marker = "<!-- Generated by pstack OpenCode routing. -->";

export const opencode = {
  id: "pstack-opencode",
  harness: "opencode",
  marker,
  route(label, { model, effort: variant }) {
    if (model === null) {
      if (variant !== null) throw new Error(`Cannot apply explicit effort to inherited OpenCode model for ${label}`);
      return { target: { agent: "general", model: "inherit-parent" } };
    }
    if (!/^[a-z0-9._-]+\/[a-z0-9._-]+$/.test(model)) {
      throw new Error(`Invalid model assignment for ${label}: ${model}`);
    }
    if (variant !== null && !/^[a-z0-9_-]+$/.test(variant)) {
      throw new Error(`Invalid reasoning variant for ${model}`);
    }
    const reference = variant === null ? model : `${model}#${variant}`;
    const agent = core.agentName(reference);
    return { target: { agent, model, variant }, profile: { agent, key: reference, text: profileText(reference) } };
  },
};

export function profileText(reference) {
  return `---
description: Pstack worker routed to ${reference}. Use for roles assigned to this model in pstack-models.md.
mode: subagent
model: ${reference}
---

${core.workerBrief(marker)}`;
}

export const routesFromSheet = (text) => core.routesFromSheet(text, opencode);
export const installProfiles = (mapping, configDir, options) => core.installProfiles(mapping, configDir, opencode, options);
export const main = (args) => core.main(args, opencode);

core.runIfMain(import.meta.url, opencode);
